"""Read-only discovery and stateless planning: no billing, filings or DB writes."""
from typing import Literal
from fastapi import APIRouter
from pydantic import BaseModel, Field, field_validator
from .catalog import STATES, ENTITY_TYPES, OWNERSHIP_TYPES, service_records
from ..services.execution_hub import CATALOG, connection_status
from .locales import LANGUAGES
from ..services.official_resources import public_resources

router = APIRouter(prefix="/api/v2", tags=["Genesis OS 2.0 development"])


class Intake(BaseModel):
    stage: Literal["start", "run", "grow"]
    state: str
    entity_type: str
    ownership_type: str = "Independent business"
    goal: str = Field(min_length=5, max_length=1200)

    @field_validator("goal", mode="before")
    @classmethod
    def clean_goal(cls, value):
        return value.strip() if isinstance(value, str) else value

    @field_validator("state")
    @classmethod
    def valid_state(cls, value):
        if value not in dict(STATES):
            raise ValueError("Choose one of the 50 supported states")
        return value

    @field_validator("entity_type")
    @classmethod
    def valid_entity(cls, value):
        if value not in ENTITY_TYPES:
            raise ValueError("Choose a supported entity type")
        return value

    @field_validator("ownership_type")
    @classmethod
    def valid_ownership(cls, value):
        if value not in OWNERSHIP_TYPES:
            raise ValueError("Choose a supported ownership structure")
        return value


@router.get("/catalog")
def catalog():
    return {
        "version": "2.0-development",
        "languages": LANGUAGES,
        "official_resources": public_resources(),
        "states": [{"code": code, "name": name} for code, name in STATES],
        "entity_types": ENTITY_TYPES,
        "ownership_types": OWNERSHIP_TYPES,
        "services": service_records(),
        "ai": {"status": "AWAITING_APPROVAL", "mode": "GUIDED_PLANNING", "live_enabled": False,
               "notice": "Planning uses transparent rules. Saved consultations offer a labeled no-cost simulation, not live AI."},
        "billing": {"status": "PRICING_NOT_APPROVED", "checkout_enabled": False},
        "providers": [
            {"name": "SendGrid", "status": connection_status(CATALOG["email_send"])["state"]},
            {"name": "Square", "status": connection_status(CATALOG["crm_customer_create"])["state"]},
        ],
        "notice": "All 50 states are selectable for planning. No state filing API or legal determination is provided.",
    }


@router.post("/plan")
def plan(intake: Intake):
    services = [service for service in service_records() if service["stage"] == intake.stage]
    return {
        "mode": "GUIDED_PLANNING",
        "persisted": False,
        "intake": intake.model_dump(),
        "state_name": dict(STATES)[intake.state],
        "steps": [
            {
                "order": index + 1,
                "service_id": service["id"],
                "title": service["title"],
                "next_action": service["description"],
                "status": service["availability"],
                "professional_review": service["professional_review"],
                "official_url": service["official_url"],
                "price_cents": None,
                "completed": False,
            }
            for index, service in enumerate(services)
        ],
        "approvals": ["No purchases, government filings or external submissions are authorized by this plan."],
        "notice": (
            "Preliminary checklist, not state-specific legal, tax or financial advice. "
            "Your goal is recorded as context; the checklist is selected by stage, not generated by AI. "
            "Holding companies and subsidiaries describe ownership, not separate legal entity types. "
            "Review details with qualified professionals. This preview does not save your answers."
        ),
    }
