"""New preview contracts only; never write to the running application's DB."""
from fastapi import FastAPI
from fastapi.testclient import TestClient
import pytest
from app.v2.router import router


@pytest.fixture()
def client():
    app = FastAPI()
    app.include_router(router)
    with TestClient(app) as test_client:
        yield test_client


def intake(**changes):
    result = dict(
        stage="start", state="NY", entity_type="LLC",
        ownership_type="Independent business",
        goal="Launch a neighborhood consulting business",
    )
    return {**result, **changes}


def test_catalog_has_50_unique_states_and_honest_service_gates(client):
    data = client.get("/api/v2/catalog").json()
    assert len(data["states"]) == len({state["code"] for state in data["states"]}) == 50
    assert len(data["services"]) == 17
    assert {service["stage"] for service in data["services"]} == {"start", "run", "grow"}
    assert not data["billing"]["checkout_enabled"]
    assert all(service["price_cents"] is None for service in data["services"])
    assert all(not service["submission_available"] for service in data["services"])
    assert all(provider["status"] != "CONNECTED" for provider in data["providers"])
    assert data["ai"]["mode"] == "GUIDED_PLANNING"


@pytest.mark.parametrize("stage", ["start", "run", "grow"])
def test_plans_are_stateless_unexecuted_stage_checklists(client, stage):
    payload = intake()
    payload["stage"] = stage
    response = client.post("/api/v2/plan", json=payload)
    assert response.status_code == 200
    plan = response.json()
    assert plan["intake"] == payload
    assert not plan["persisted"]
    assert plan["state_name"] == "New York"
    assert plan["steps"]
    assert all(not step["completed"] for step in plan["steps"])
    catalog = client.get("/api/v2/catalog").json()
    assert {step["service_id"] for step in plan["steps"]} == {
        service["id"] for service in catalog["services"] if service["stage"] == stage
    }
    assert all(step["price_cents"] is None for step in plan["steps"])
    assert "not generated by AI" in plan["notice"]


@pytest.mark.parametrize("key,value", [
    ("state", "ZZ"), ("stage", "file_now"), ("entity_type", "Holding company"),
    ("ownership_type", "Unknown structure"), ("goal", "    "),
    ("goal", "x" * 1201),
])
def test_invalid_intake_rejected(client, key, value):
    payload = intake()
    payload[key] = value
    assert client.post("/api/v2/plan", json=payload).status_code == 422


def test_every_state_is_selectable_without_claiming_a_state_filing_api(client):
    for state in client.get("/api/v2/catalog").json()["states"]:
        payload = intake()
        payload["state"] = state["code"]
        result = client.post("/api/v2/plan", json=payload).json()
        assert result["state_name"] == state["name"]
        assert result["mode"] == "GUIDED_PLANNING"


def test_holding_ownership_kept_separate_from_legal_entity(client):
    payload = intake()
    payload["ownership_type"] = "Holding company"
    response = client.post("/api/v2/plan", json=payload)
    assert response.status_code == 200
    assert response.json()["intake"]["entity_type"] == "LLC"
